def main():
    by_path = {p["path"]: p for p in PAGES}

    def cards(pages):
        return '<ul class="cards">' + "".join(
            f'<li><a href="{p["path"]}"><span class="t">{html.escape(p["card_title"])}</span>'
            f'<span class="d">{html.escape(p["card_desc"])}</span></a></li>'
            for p in pages
        ) + "</ul>"

    # 関連記事は同じカテゴリ内の記事にする（16本すべてを並べても選べないため）
    for title, _, paths in CATEGORIES:
        for path in paths:
            page = by_path[path]
            page["_related"] = [by_path[q] for q in paths if q != path]
            page["_category"] = title

    # ガイド一覧をカテゴリ別に組み立てる
    guide_index = by_path["/guide/"]
    cat_html = "".join(
        f'<h2 class="serif" id="cat-{n}">{html.escape(title)}</h2>'
        f"<p>{html.escape(desc)}</p>" + cards([by_path[p] for p in paths])
        for n, (title, desc, paths) in enumerate(CATEGORIES, 1)
    )
    guide_index["blocks"] = [
        ("raw", cat_html) if b[0] == "cats" else b for b in guide_index["blocks"]
    ]

    for page in PAGES:
        out_dir = os.path.join(ROOT, page["path"].strip("/"))
        os.makedirs(out_dir, exist_ok=True)
        out = os.path.join(out_dir, "index.html")
        with open(out, "w", encoding="utf-8") as f:
            f.write(render_page(page, GUIDE_ARTICLES))
        print("wrote", os.path.relpath(out, ROOT))

    # sitemap
    entries = [("/", "1.0", "monthly"), ("/guide/", "0.8", "monthly"), ("/faq/", "0.7", "monthly")]
    # 主力機能（ジェノグラム・エコマップ）の記事は優先度を上げる
    main_paths = set(CATEGORIES[0][2])
    entries += [
        (p["path"], "0.9" if p["path"] in main_paths else "0.7", "monthly")
        for p in GUIDE_ARTICLES
    ]
    urls = "\n".join(
        f"  <url>\n    <loc>{SITE}{path}</loc>\n    <lastmod>{UPDATED}</lastmod>\n"
        f"    <changefreq>{freq}</changefreq>\n    <priority>{pri}</priority>\n  </url>"
        for path, pri, freq in entries
    )
    sitemap = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"{urls}\n</urlset>\n"
    )
    with open(os.path.join(ROOT, "sitemap.xml"), "w", encoding="utf-8") as f:
        f.write(sitemap)
    print("wrote sitemap.xml", f"({len(entries)} urls)")


if __name__ == "__main__":
    main()
